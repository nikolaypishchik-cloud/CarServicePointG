#include <QSet>
#include <QSqlDatabase>
#include <QSqlQuery>

namespace {
int scalarCount(QSqlDatabase db, const QString& sql)
{
    QSqlQuery q(db);
    if (!q.exec(sql) || !q.next()) {
        return -1;
    }
    return q.value(0).toInt();
}

QSet<QString> tableColumns(QSqlDatabase db, const QString& schemaName, const QString& tableName)
{
    QSet<QString> cols;
    QSqlQuery q(db);
    const QString pragmaName = schemaName.trimmed().isEmpty()
        ? tableName
        : QStringLiteral("%1.table_info(%2)").arg(schemaName, tableName);
    if (!q.exec(QStringLiteral("PRAGMA %1").arg(pragmaName))) {
        return cols;
    }
    while (q.next()) {
        cols.insert(q.value(1).toString().trimmed());
    }
    return cols;
}

QString firstAvailableExpr(const QSet<QString>& cols, const QStringList& candidates, const QString& fallback)
{
    for (const QString& candidate : candidates) {
        if (cols.contains(candidate)) {
            return candidate;
        }
    }
    return fallback;
}

LegacyImportVerifyEntityResult exactEntityResult(QSqlDatabase db,
                                                 const QString& entityName,
                                                 const QString& sourceCountSql,
                                                 const QString& targetCountSql,
                                                 const QString& missingSql,
                                                 const QString& invalidSql = QString())
{
    LegacyImportVerifyEntityResult result;
    result.entityName = entityName;
    result.sourceCount = scalarCount(db, sourceCountSql);
    result.targetCount = scalarCount(db, targetCountSql);
    result.missingCount = missingSql.isEmpty() ? 0 : scalarCount(db, missingSql);
    result.invalidLinkCount = invalidSql.isEmpty() ? 0 : scalarCount(db, invalidSql);
    const QString baselineEntity = entityName=="personnel" ? QStringLiteral("masters") : QStringLiteral("work_order_parts");
    const qint64 retained = MigrationDestinationBaseline::before(db,baselineEntity);
    result.ok = result.sourceCount >= 0
        && result.targetCount >= 0
        && retained >= 0 && retained + result.sourceCount == result.targetCount
        && result.missingCount == 0
        && result.invalidLinkCount == 0;
    if (retained < 0 || retained + result.sourceCount != result.targetCount) {
        result.messages << QStringLiteral("sourceCount=%1 targetCount=%2").arg(result.sourceCount).arg(result.targetCount);
    }
    if (result.missingCount > 0) {
        result.messages << QStringLiteral("missing=%1").arg(result.missingCount);
    }
    if (result.invalidLinkCount > 0) {
        result.messages << QStringLiteral("invalidLinks=%1").arg(result.invalidLinkCount);
    }
    return result;
}

LegacyImportVerifyEntityResult relaxedServiceMastersResult(QSqlDatabase db,
                                                           const QString& sourceCountSql,
                                                           const QString& targetCountSql,
                                                           const QString& missingSql,
                                                           const QString& invalidSql)
{
    LegacyImportVerifyEntityResult result;
    result.entityName = QStringLiteral("service_masters");
    result.sourceCount = scalarCount(db, sourceCountSql);
    result.targetCount = scalarCount(db, targetCountSql);
    result.missingCount = scalarCount(db, missingSql);
    result.invalidLinkCount = scalarCount(db, invalidSql);
    const bool countOk = result.sourceCount >= 0 && result.targetCount >= result.sourceCount;
    result.ok = countOk && result.missingCount == 0 && result.invalidLinkCount == 0;
    if (!countOk) {
        result.messages << QStringLiteral("sourceCount=%1 targetCount=%2").arg(result.sourceCount).arg(result.targetCount);
    } else if (result.targetCount > result.sourceCount) {
        result.messages << QStringLiteral("targetHasAutoGeneratedLinks=%1").arg(result.targetCount - result.sourceCount);
    }
    if (result.missingCount > 0) {
        result.messages << QStringLiteral("missing=%1").arg(result.missingCount);
    }
    if (result.invalidLinkCount > 0) {
        result.messages << QStringLiteral("invalidLinks=%1").arg(result.invalidLinkCount);
    }
    return result;
}
}

void LegacyImportEntityVerifySupport::appendEntityResults(QSqlDatabase db, LegacyImportVerifyReport* report)
{
    if (!report) return;

    const QSet<QString> srcParts = tableColumns(db, QStringLiteral("verify_src"), QStringLiteral("work_order_parts"));
    if (srcParts.size() > 0) {
        const QString srcPartIdExpr = firstAvailableExpr(srcParts, {QStringLiteral("id")}, QStringLiteral("id"));
        const QString srcPartOrderExpr = firstAvailableExpr(srcParts,
            {QStringLiteral("order_number"), QStringLiteral("work_order"), QStringLiteral("work_order_id"), QStringLiteral("work_order_number")},
            QStringLiteral("order_number"));
        const QString srcPartIdSql = QStringLiteral("s.%1").arg(srcPartIdExpr);
        const QString srcPartOrderSql = QStringLiteral("s.%1").arg(srcPartOrderExpr);
        report->entities.push_back(exactEntityResult(
            db,
            QStringLiteral("parts"),
            QStringLiteral("SELECT COUNT(*) FROM verify_src.work_order_parts"),
            QStringLiteral("SELECT COUNT(*) FROM work_order_parts"),
            QStringLiteral("SELECT COUNT(*) FROM verify_src.work_order_parts s LEFT JOIN work_order_parts t ON t.id=%1 AND t.order_number=%2 WHERE t.id IS NULL")
                .arg(srcPartIdSql, srcPartOrderSql),
            QStringLiteral("SELECT COUNT(*) FROM work_order_parts p LEFT JOIN work_order_services s ON s.id=p.service_id WHERE COALESCE(p.service_id,0)<>0 AND (s.id IS NULL OR COALESCE(s.order_number,0)<>COALESCE(p.order_number,0))")));

        const int partAmountMismatches = scalarCount(db, QStringLiteral(
            "SELECT COUNT(*) FROM work_order_parts WHERE ABS(COALESCE(amount,0) - ROUND(COALESCE(qty,1) * COALESCE(price,0), 2)) > 0.009"));
        if (partAmountMismatches > 0) {
            report->warningMessages << QStringLiteral("Після імпорту залишилися запчастини з розбіжністю amount і qty*price: %1").arg(partAmountMismatches);
        }
    }

    const QSet<QString> srcMasters = tableColumns(db, QStringLiteral("verify_src"), QStringLiteral("masters"));
    if (srcMasters.size() > 0) {
        report->entities.push_back(exactEntityResult(
            db,
            QStringLiteral("personnel"),
            QStringLiteral("SELECT COUNT(*) FROM verify_src.masters"),
            QStringLiteral("SELECT COUNT(*) FROM masters"),
            QStringLiteral("SELECT COUNT(*) FROM verify_src.masters s LEFT JOIN masters t ON t.id=s.id WHERE t.id IS NULL"),
            QStringLiteral("SELECT "
                           "(SELECT COUNT(*) FROM work_orders o LEFT JOIN masters m ON m.id=o.master_id WHERE TRIM(COALESCE(o.master_id,''))<>'' AND m.id IS NULL) + "
                           "(SELECT COUNT(*) FROM service_masters sm LEFT JOIN masters m ON m.id=sm.master_id WHERE m.id IS NULL)")));
    }

    const QSet<QString> srcServiceMasters = tableColumns(db, QStringLiteral("verify_src"), QStringLiteral("service_masters"));
    if (srcServiceMasters.size() > 0) {
        report->entities.push_back(relaxedServiceMastersResult(
            db,
            QStringLiteral("SELECT COUNT(*) FROM verify_src.service_masters"),
            QStringLiteral("SELECT COUNT(*) FROM service_masters"),
            QStringLiteral("SELECT COUNT(*) FROM verify_src.service_masters s LEFT JOIN service_masters t ON t.service_id=s.service_id AND t.master_id=s.master_id WHERE t.service_id IS NULL"),
            QStringLiteral("SELECT "
                           "(SELECT COUNT(*) FROM service_masters sm LEFT JOIN work_order_services s ON s.id=sm.service_id WHERE s.id IS NULL) + "
                           "(SELECT COUNT(*) FROM service_masters sm LEFT JOIN masters m ON m.id=sm.master_id WHERE m.id IS NULL)")));

        const int nonPositiveShares = scalarCount(db, QStringLiteral("SELECT COUNT(*) FROM service_masters WHERE COALESCE(share_percent,0)<=0"));
        if (nonPositiveShares > 0) {
            report->warningMessages << QStringLiteral("Після імпорту залишилися service_masters з share_percent<=0: %1").arg(nonPositiveShares);
        }
    }

    const int crossOrderParents = scalarCount(db, QStringLiteral(
        "SELECT COUNT(*) FROM work_order_services c JOIN work_order_services p ON p.id=c.parent_id WHERE COALESCE(c.parent_id,0)<>0 AND COALESCE(c.order_number,0)<>COALESCE(p.order_number,0)"));
    if (crossOrderParents > 0) {
        LegacyImportVerifyEntityResult result;
        result.entityName = QStringLiteral("services.parent_scope");
        result.invalidLinkCount = crossOrderParents;
        result.ok = false;
        result.messages << QStringLiteral("invalidLinks=%1").arg(crossOrderParents);
        report->entities.push_back(result);
    }
}
