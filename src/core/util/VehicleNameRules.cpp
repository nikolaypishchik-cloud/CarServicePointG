QString normalizeBrandSpecificModels(QString text)
{
    auto items = targetedBrandModels();
    std::sort(items.begin(), items.end(), [](const auto& a, const auto& b) {
        return a.first.size() > b.first.size();
    });

    for (const auto& entry : items) {
        const QString brand = entry.first;
        if (!text.contains(brand, Qt::CaseInsensitive)) continue;
        QStringList models = entry.second;
        std::sort(models.begin(), models.end(), [](const QString& a, const QString& b) {
            return a.size() > b.size();
        });
        const QString brandPattern = QRegularExpression::escape(brand);
        for (const QString& model : models) {
            const QString modelPattern = buildFlexibleModelPattern(model);
            const QRegularExpression re(
                QStringLiteral(R"((?i)(?<![\p{L}\p{N}])(%1)\s+%2(?![\p{L}\p{N}]))").arg(brandPattern, modelPattern));
            text.replace(re, QStringLiteral("\\1 %1").arg(model));
        }
    }
    return text;
}


