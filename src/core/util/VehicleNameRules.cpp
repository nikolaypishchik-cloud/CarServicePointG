QString buildFlexibleModelPattern(QString value)
{
    value = value.trimmed().toLower();
    QString pattern;
    pattern.reserve(value.size() * 3);
    for (const QChar& ch : value) {
        if (ch.isSpace() || ch == QChar('-') || ch == QChar('.') || ch == QChar('/')) {
            pattern += QStringLiteral(R"((?:[\s\.-\/]*))");
        } else {
            pattern += QRegularExpression::escape(QString(ch));
        }
    }
    return pattern;
}

